class PillButton(tk.Canvas):
    """A rounded, flat button drawn on a Canvas (pill shape)."""

    def __init__(self, master, text, command, width=116, height=38,
                 kind="ghost", selectable=False):
        super().__init__(master, width=width, height=height, bg=BG,
                         highlightthickness=0, bd=0, cursor="hand2")
        self.text = text
        self.command = command
        self.kind = kind
        self.selectable = selectable
        self.selected = False
        self._hover = False
        self._pw = width
        self._ph = height
        self.bind("<Enter>", lambda e: self._set_hover(True))
        self.bind("<Leave>", lambda e: self._set_hover(False))
        self.bind("<Button-1>", self._on_click)
        self._draw()

    def _set_hover(self, on):
        self._hover = on
        self._draw()

    def set_selected(self, selected):
        self.selected = selected
        self._draw()

    def _on_click(self, _event=None):
        if self.command:
            self.command()

    def _draw(self):
        self.delete("all")
        w, h = self._pw, self._ph
        r = h / 2
        fill, outline, fg = BG, BORDER, TEXT_2
        if self.kind == "accent":
            fill = "#c9f6e9" if self._hover else ACCENT
            outline = ACCENT
            fg = ACCENT_DK
        elif self.selectable and self.selected:
            fill = ACCENT_BG
            outline = ACCENT_DIM
            fg = ACCENT
        elif self._hover:
            outline = "#4b4b45"
            fg = TEXT
        self._round_rect(1, 1, w - 1, h - 1, r, fill=fill, outline=outline, width=1)
        self.create_text(w / 2, h / 2, text=self.text, fill=fg, font=FONT_BOLD)

    def _round_rect(self, x1, y1, x2, y2, r, **kw):
        pts = [x1 + r, y1, x2 - r, y1, x2, y1, x2, y1 + r,
               x2, y2 - r, x2, y2, x2 - r, y2, x1 + r, y2,
               x1, y2, x1, y2 - r, x1, y1 + r, x1, y1]
        return self.create_polygon(pts, smooth=True, **kw)


class Dial(tk.Canvas):
    """A rotary gauge (Ookla-speedtest style): a 180° semicircular arc over a large
    centred value, with tick marks and no needle — the accent arc sweeps clockwise
    from the left to show the value. Scroll to turn, click the value to type.
    """

    def __init__(self, master, label, min_val, max_val, value, fmt=None,
                 to_raw=None, parse=None, log=False, step=0.02, on_change=None,
                 warn=None, diameter=120, enabled=True):
        super().__init__(master, width=diameter, height=diameter + 26, bg=PANEL,
                         highlightthickness=0, bd=0)
        self._label = label
        self._min = min_val
        self._max = max_val
        self._log = log
        self._step = step
        self._value = value
        self._fmt = fmt or (lambda v: f"{v:g}")
        self._to_raw = to_raw or (lambda v: f"{v:g}")
        self._parse = parse or (lambda t: float(t))
        self._on_change = on_change
        self._warn = warn
        self._enabled = enabled
        self._editing = False
        self._entry = None
        self._win = None
        self._d = diameter

        self.bind("<Enter>", self._on_enter)
        self.bind("<MouseWheel>", self._on_wheel)
        self.bind("<Button-4>", self._on_wheel)
        self.bind("<Button-5>", self._on_wheel)
        self.bind("<Button-1>", self._on_click)
        self._draw()

    def reconfig(self, label=None, min_val=None, max_val=None, value=None,
                 fmt=None, to_raw=None, parse=None, log=None, step=None):
        if label is not None:
            self._label = label
        if min_val is not None:
            self._min = min_val
        if max_val is not None:
            self._max = max_val
        if fmt is not None:
            self._fmt = fmt
        if to_raw is not None:
            self._to_raw = to_raw
        if parse is not None:
            self._parse = parse
        if log is not None:
            self._log = log
        if step is not None:
            self._step = step
        if value is not None:
            self._value = clamp(value, self._min, self._max)
        self._draw()

    # ----- mapping -----
    def _t(self, v):
        if self._log:
            return (math.log10(v) - math.log10(self._min)) / (
                math.log10(self._max) - math.log10(self._min))
        return (v - self._min) / (self._max - self._min)

    def _v(self, t):
        t = clamp(t, 0.0, 1.0)
        if self._log:
            return self._min * (self._max / self._min) ** t
        return self._min + t * (self._max - self._min)

    def set_enabled(self, enabled):
        self._enabled = enabled
        self.configure(cursor="hand2" if enabled else "arrow")
        self._draw()

    def get_value(self):
        return self._value

    def set_value(self, value):
        self._value = clamp(value, self._min, self._max)
        self._draw()

    # ----- events -----
    def _on_enter(self, _e):
        if self._enabled:
            self.focus_set()

    def _on_wheel(self, e):
        if not self._enabled or self._editing:
            return
        delta = getattr(e, "delta", 0)
        num = getattr(e, "num", 0)
        if num == 4 or delta > 0:
            d = +1
        elif num == 5 or delta < 0:
            d = -1
        else:
            return
        step = self._step
        if getattr(e, "state", 0) & 0x0001:  # Shift = fine
            step /= 10.0
        self._value = self._v(self._t(self._value) + d * step)
        self._draw()
        if self._on_change:
            self._on_change(self._value)

    def _on_click(self, _e):
        if not self._enabled or self._editing:
            return
        self._editing = True
        self._entry = tk.Entry(self, bg=PANEL_2, fg=TEXT, insertbackground=ACCENT,
                               relief="flat", justify="center", font=FONT_BOLD,
                               highlightthickness=1, highlightbackground=ACCENT_DIM,
                               highlightcolor=ACCENT, width=10)
        self._entry.insert(0, self._to_raw(self._value))
        self._entry.select_range(0, "end")
        self._win = self.create_window(self._d / 2, self._d / 2 + 6, window=self._entry)
        self._entry.focus_set()
        self._entry.bind("<Return>", self._commit)
        self._entry.bind("<Escape>", self._cancel)
        self._entry.bind("<FocusOut>", self._commit)

    def _commit(self, _e=None):
        if not self._editing:
            return
        try:
            v = self._parse(self._entry.get())
        except (ValueError, TypeError):
            self._cancel()
            return
        self._finish_edit()
        self.set_value(v)
        if self._on_change:
            self._on_change(self._value)

    def _cancel(self, _e=None):
        if self._editing:
            self._finish_edit()
            self._draw()

    def _finish_edit(self):
        self._editing = False
        if self._win is not None:
            self.delete(self._win)
            self._win = None
        if self._entry is not None:
            self._entry.destroy()
            self._entry = None

    # ----- draw -----
    def _arc(self, bbox, f0, f1, color, width=5):
        self.create_arc(bbox, start=180 * (1.0 - f0), extent=-180 * (f1 - f0),
                        style="arc", outline=color, width=width)

    def _draw(self):
        self.delete("all")
        d = self._d
        cx = d / 2
        cy = d / 2
        r = d / 2 - 6
        bbox = (cx - r, cy - r, cx + r, cy + r)
        t = self._t(self._value)
        accent = ACCENT if self._enabled else FAINT
        track = BORDER if self._enabled else "#1e1e1e"
        warn_fill = WARN if self._enabled else FAINT
        warn_dim = WARN_DIM if self._enabled else track
        warn_t = self._t(self._warn) if self._warn is not None else None

        # semicircular track over the top, min at left (180°) -> max at right (0°)
        self._arc(bbox, 0.0, 1.0, track)

        # static warning band from the threshold to max (signal-quality loss zone)
        if warn_t is not None and warn_t < 1.0:
            self._arc(bbox, warn_t, 1.0, warn_dim)

        # filled arc sweeps clockwise from the left over the top
        if t > 0.001:
            if warn_t is not None and t > warn_t:
                self._arc(bbox, 0.0, warn_t, accent)
                self._arc(bbox, warn_t, t, warn_fill)
            else:
                self._arc(bbox, 0.0, t, accent)

        # tick marks just outside the arc
        n_ticks = 10
        for i in range(n_ticks + 1):
            a = math.radians(180 - 180 * i / n_ticks)
            cos_a, sin_a = math.cos(a), math.sin(a)
            self.create_line(cx + r * cos_a, cy - r * sin_a,
                             cx + (r + 5) * cos_a, cy - (r + 5) * sin_a,
                             fill=FAINT, width=1)

        # large centred value
        fg = TEXT if self._enabled else FAINT
        self.create_text(cx, cy + 6, text=self._fmt(self._value), fill=fg,
                         font=("Segoe UI", 17, "bold"))

        # label below
        self.create_text(cx, d + 12, text=self._label,
                         fill=MUTED if self._enabled else FAINT,
                         font=("Segoe UI", 8, "bold"))


