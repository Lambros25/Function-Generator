    # --------------------------------------------------------------- Serial
    def _refresh_ports(self):
        ports = [p.device for p in list_ports.comports()]
        self.port_menu.delete(0, "end")
        if not ports:
            self.port_var.set("")
            self.port_menu.add_command(label="No ports", state="disabled")
            return
        best = None
        for p in list_ports.comports():
            blob = " ".join(filter(None, [p.device, p.description or "", p.hwid or ""])).lower()
            if "pico" in blob or "2e8a" in blob or "usb serial" in blob:
                best = p.device
                break
        chosen = best or ports[0]
        self.port_var.set(chosen)
        for p in ports:
            self.port_menu.add_command(label=p, command=lambda v=p: self.port_var.set(v))

    def _toggle_connect(self):
        if self.ser is not None:
            self._disconnect()
            return
        port = self.port_var.get()
        if not port:
            self._notice("No serial port selected.")
            return
        try:
            self.ser = serial.Serial(port, BAUD, timeout=0.1)
        except serial.SerialException:
            self._notice(f"Could not open {port}.")
            return
        self.stop_event.clear()
        self.reader_thread = threading.Thread(target=self._reader_loop, daemon=True)
        self.reader_thread.start()
        self.connect_btn.text = "Disconnect"
        self.connect_btn._draw()
        self.status_lbl.config(text=f"●  Connected  ·  {port}", fg=ACCENT)
        self._notice("")
        self._log(f"Connected to {port}")
        self._send("i")

    def _disconnect(self):
        self.stop_event.set()
        if self.ser is not None:
            try:
                self.ser.close()
            except serial.SerialException:
                pass
            self.ser = None
        self.connect_btn.text = "Connect"
        self.connect_btn._draw()
        self.status_lbl.config(text="●  Disconnected", fg=FAINT)

    def _reader_loop(self):
        buf = ""
        while not self.stop_event.is_set():
            try:
                chunk = self.ser.read(self.ser.in_waiting or 1)
            except serial.SerialException:
                break
            if chunk:
                buf += chunk.decode("utf-8", errors="replace")
                while "\n" in buf:
                    line, buf = buf.split("\n", 1)
                    self.rx_queue.put(line.rstrip("\r") + "\n")
        if buf:
            self.rx_queue.put(buf)

    def _poll_rx(self):
        try:
            while True:
                data = self.rx_queue.get_nowait()
                self._log(data)
        except queue.Empty:
            pass
        self.root.after(50, self._poll_rx)

    def _send(self, cmd):
        if self.ser is None:
            return
        try:
            self.ser.write((cmd + "\n").encode("utf-8"))
        except serial.SerialException:
            self._disconnect()

    def _log(self, text):
        self.log.config(state="normal")
        for line in text.splitlines():
            self.log.insert("end", line + "\n")
        if int(self.log.index("end-1c").split(".")[0]) > 500:
            self.log.delete("1.0", "200.0")
        self.log.see("end")
        self.log.config(state="disabled")

    def _notice(self, text):
        self.notice_lbl.config(text=text)

    # -------------------------------------------------------------- Actions
    def _set_mode(self, mode, send=True):
        self.mode = mode
        for val, b in self.mode_btns.items():
            b.set_selected(val == mode)
        if send:
            self._send(mode)
        self._notice("")
        self._update_dials_for_mode()
        self._update_help()
        self.draw_preview()

    def _update_dials_for_mode(self):
        m = self.mode
        self.cal_dial.set_enabled(m != "square")
        self.snr_dial.set_enabled(m == "noise")
        self.mod_freq_dial.set_enabled(m in ("am", "fm"))
        self.mod_amount_dial.set_enabled(m in ("am", "fm"))
        if m == "am":
            self.mod_amount_dial.reconfig(
                label="DEPTH (%)", min_val=0.0, max_val=100.0, value=self.mod_amount,
                log=False, fmt=lambda v: f"{v:.0f}%", to_raw=lambda v: f"{v:.1f}",
                parse=float, step=0.01)
        elif m == "fm":
            self.mod_amount_dial.reconfig(
                label="DEVIATION (Hz)", min_val=1.0, max_val=100000.0, value=self.mod_amount,
                log=True, fmt=fmt_freq, to_raw=lambda v: f"{v:.1f}",
                parse=float, step=0.004)

    def _set_freq(self, v):
        self.freq = v
        self._send(f"f{int(round(v))}")
        self.draw_preview()

    def _set_cal(self, v):
        self.cal = v
        self._send(f"c{v:g}")

    def _set_snr(self, v):
        self.snr = v
        self._send(f"snr{v:g}")
        self.draw_preview()

    def _set_mod_freq(self, v):
        self.mod_freq = v
        self._send(f"m{int(round(v))}")

    def _set_mod_amount(self, v):
        self.mod_amount = v
        self._send(f"d{v:g}")
        self.draw_preview()

    # -------------------------------------------------------------- Preview
    def draw_preview(self):
        c = self.canvas
        c.delete("all")
        c.update_idletasks()
        w = c.winfo_width() or 560
        h = c.winfo_height() or 210
        pad_x, pad_y = 12, 14

        def y(code):
            return pad_y + (1.0 - code / DAC_FULL) * (h - 2 * pad_y)

        N = 512
        t = self._preview_t

        def x_of(i):
            return pad_x + (i / N) * (w - 2 * pad_x)

        mode = self.mode

        if mode == "square":
            pts = []
            for i in range(N + 1):
                ang = (i / N) * 4 * math.pi
                code = DAC_FULL if math.sin(ang) >= 0 else 0
                pts.append((x_of(i), y(code)))
            self._polyline(pts, ACCENT, 2)
            title = "square"
        elif mode == "noise":
            a, s = amp_from_snr(self.snr)
            pts_sine, pts_sum = [], []
            for i in range(N + 1):
                ang = (i / N) * 4 * math.pi
                sine_code = DAC_MID + a * math.sin(ang)
                pts_sine.append((x_of(i), y(sine_code)))
                pts_sum.append((x_of(i), y(clamp(sine_code + random.gauss(0.0, s), 0, DAC_FULL))))
            self._polyline(pts_sine, TEXT_2, 1, dash=(2, 2))
            self._polyline(pts_sum, ACCENT, 2)
            title = f"sine + noise  ·  SNR {self.snr:.1f} dB"
        elif mode == "am":
            depth = clamp(self.mod_amount / 100.0, 0.0, 1.0)
            amp = 127.0 / (1.0 + depth)
            pts = []
            for i in range(N + 1):
                x = i / N
                carrier = x * 20 * 2 * math.pi
                modph = x * 2 * 2 * math.pi + t
                code = clamp(DAC_MID + amp * (1.0 + depth * math.sin(modph)) * math.sin(carrier), 0, DAC_FULL)
                pts.append((x_of(i), y(code)))
            self._polyline(pts, ACCENT, 2)
            title = f"AM  ·  depth {self.mod_amount:.0f}%"
        elif mode == "fm":
            beta = clamp(self.mod_amount / 1000.0, 0.0, 12.0)
            pts = []
            for i in range(N + 1):
                x = i / N
                carrier = x * 20 * 2 * math.pi
                modph = x * 2 * 2 * math.pi + t
                code = clamp(DAC_MID + 127.0 * math.sin(carrier + beta * math.sin(modph)), 0, DAC_FULL)
                pts.append((x_of(i), y(code)))
            self._polyline(pts, ACCENT, 2)
            title = f"FM  ·  dev {self.mod_amount:g} Hz"
        else:
            pts = []
            for i in range(N + 1):
                ang = (i / N) * 4 * math.pi
                pts.append((x_of(i), y(DAC_MID + 127.5 * math.sin(ang))))
            self._polyline(pts, ACCENT, 2)
            title = "sine"

        c.create_text(14, 14, text=title, anchor="nw", fill=MUTED, font=FONT_MONO)
        c.create_text(w - 14, 14, text=fmt_freq(self.freq) + " Hz", anchor="ne",
                      fill=FAINT, font=FONT_MONO)

    def _polyline(self, pts, color, width=2, dash=None):
        self.canvas.create_line(*[v for p in pts for v in p], fill=color,
                                width=width, dash=dash)

    def _animate(self):
        if self.mode in ("am", "fm", "noise"):
            self._preview_t += 0.12
            self.draw_preview()
        self.root.after(50, self._animate)

    def _update_help(self):
        self.help_lbl.config(text=HELP_TEXT[self.mode])

    def on_close(self):
        self._disconnect()
        self.root.destroy()


