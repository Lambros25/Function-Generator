def amp_from_snr(snr_db):
    """Return (sine peak amplitude A, noise sigma s) in DAC codes for a given SNR."""
    r = 10.0 ** (snr_db / 20.0)
    s = HEADROOM / (math.sqrt(2.0) * r + 4.0)
    a = math.sqrt(2.0) * r * s
    return a, s


def clamp(v, lo, hi):
    return max(lo, min(hi, v))


def fmt_freq(v):
    if v >= 1e6:
        return f"{v / 1e6:.2f}M"
    if v >= 1e3:
        return f"{v / 1e3:.2f}k"
    return f"{v:.0f}"


